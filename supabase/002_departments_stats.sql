-- 내 환자의 모든 것 · 2단계: 진료과 + 경영 통계 권한
--
-- Supabase 대시보드 → SQL Editor → New query 에 통째로 붙여넣고 [Run].
-- (schema.sql 을 이미 실행한 뒤에 실행하세요. 여러 번 실행해도 안전합니다)
--
-- 1) 진료과 목록 (기본 5개: 1과~5과, 이름은 앱에서 원장님이 바꿀 수 있어요)
-- 2) 예약·내원 기록마다 진료과
-- 3) 직원 목록 + 권한 (관리자 = master1, 통계 보기 권한은 관리자가 켜고 끔)

-- ───────── 1) 진료과 ─────────
create table if not exists public.departments (
  id         bigint generated by default as identity primary key,
  name       text    not null,
  sort       integer not null default 0,
  updated_at timestamptz not null default now()
);

insert into public.departments (name, sort)
select '1과', 1 where not exists (select 1 from public.departments)
union all select '2과', 2 where not exists (select 1 from public.departments)
union all select '3과', 3 where not exists (select 1 from public.departments)
union all select '4과', 4 where not exists (select 1 from public.departments)
union all select '5과', 5 where not exists (select 1 from public.departments);

-- ───────── 2) 예약·내원 기록의 진료과 ─────────
alter table public.appointments
  add column if not exists "deptId" bigint references public.departments(id) on delete set null;
create index if not exists appointments_dept_idx on public.appointments("deptId");

-- ───────── 3) 직원 목록과 권한 ─────────
create table if not exists public.staff (
  id             uuid primary key references auth.users(id) on delete cascade,
  email          text not null,
  is_admin       boolean not null default false,
  can_view_stats boolean not null default false
);

-- 새 직원 계정을 만들면 자동으로 목록에 추가
create or replace function public.add_staff_row() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.staff (id, email) values (new.id, coalesce(new.email, ''))
  on conflict (id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.add_staff_row();

-- 이미 만든 계정들도 목록에 넣기
insert into public.staff (id, email)
select id, coalesce(email, '') from auth.users
on conflict (id) do nothing;

-- master1 = 관리자 + 통계 보기
update public.staff set is_admin = true, can_view_stats = true
where lower(email) = 'master1@naver.com';

-- 지금 로그인한 사람이 관리자인지 (규칙 안에서 씀)
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select is_admin from public.staff where id = auth.uid()), false)
$$;

-- ───────── 접근 규칙 ─────────
alter table public.departments enable row level security;
alter table public.staff enable row level security;

-- 진료과: 직원 모두 보기, 이름 바꾸기·추가는 관리자만
drop policy if exists "staff read" on public.departments;
create policy "staff read" on public.departments
  for select to authenticated using (true);
drop policy if exists "admin write" on public.departments;
create policy "admin write" on public.departments
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- 직원 목록: 직원 모두 보기(자기 권한 확인용), 권한 바꾸기는 관리자만
drop policy if exists "staff read" on public.staff;
create policy "staff read" on public.staff
  for select to authenticated using (true);
drop policy if exists "admin update" on public.staff;
create policy "admin update" on public.staff
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

revoke all on public.departments, public.staff from anon;

-- 실시간 반영
do $$
