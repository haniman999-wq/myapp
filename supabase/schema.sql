-- 내 환자의 모든 것 · 공유 서버(Supabase) 데이터 구조
--
-- Supabase 대시보드 → SQL Editor 에 이 파일 내용을 통째로 붙여넣고 [Run] 하세요.
-- 한 번만 실행하면 됩니다. (다시 실행해도 안전하도록 IF NOT EXISTS 를 썼어요)
--
-- 보안 원칙
--  * 대시보드에서 "새 사용자 가입(Sign ups)"을 꺼 두고, 직원 계정은 관리자가 직접 만듭니다.
--  * 아래 규칙(RLS)으로 "로그인한 직원"만 읽고 쓸 수 있고, 로그인 안 한 사람은 아무것도 못 봅니다.
--  * 모든 직원은 같은 데이터를 봅니다 (권한 구분 없음).
--
-- 칸 이름은 앱 안(휴대폰 저장소)과 똑같이 맞췄습니다. (백업 파일을 그대로 옮길 수 있게)

-- ───────── 환자 ─────────
create table if not exists public.customers (
  id          bigint generated by default as identity primary key,
  name        text        not null,
  phone       text        not null,
  gender      text        not null,
  memo        text        not null default '',
  "herbStart" text,               -- 'yyyy-MM-dd', null = 한약 환자 아님
  "herbType"  text,               -- 'insured' | 'nonInsured'
  "herbDays"  integer,            -- 30 | 60 | 90 (비급여한약만)
  "createdAt" text        not null,
  updated_at  timestamptz not null default now(),
  updated_by  uuid        default auth.uid()
);

-- ───────── 예약 · 내원 기록 ─────────
create table if not exists public.appointments (
  id            bigint generated by default as identity primary key,
  "customerId"  bigint  not null references public.customers(id) on delete cascade,
  date          text    not null,   -- 'yyyy-MM-dd'
  status        text    not null,   -- booked | visited | noShow | cancelled
  "minuteOfDay" integer,            -- 예약 시각 (자정부터 분), null = 시간 미정
  memo          text    not null default '',
  updated_at    timestamptz not null default now(),
  updated_by    uuid    default auth.uid()
);
create index if not exists appointments_customer_idx on public.appointments("customerId");
create index if not exists appointments_date_idx on public.appointments(date);

-- ───────── 연락 기록 ('연락함' 버튼) ─────────
create table if not exists public.contact_logs (
  id            bigint generated by default as identity primary key,
  "customerId"  bigint not null references public.customers(id) on delete cascade,
  "contactedAt" text   not null,
  updated_by    uuid   default auth.uid()
);
create index if not exists contact_logs_customer_idx on public.contact_logs("customerId");

-- ───────── 한약 복약 확인 알림 ─────────
create table if not exists public.herb_alerts (
  id           bigint generated by default as identity primary key,
  "customerId" bigint  not null references public.customers(id) on delete cascade,
  date         text    not null,
  done         integer not null default 0,
  updated_at   timestamptz not null default now(),
  updated_by   uuid    default auth.uid()
);
create index if not exists herb_alerts_customer_idx on public.herb_alerts("customerId");

-- ───────── 수정 시각 자동 기록 ─────────
create or replace function public.touch_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  new.updated_by := auth.uid();
  return new;
end $$;

do $$
declare t text;
begin
  foreach t in array array['customers', 'appointments', 'herb_alerts'] loop
    execute format('drop trigger if exists touch_%1$s on public.%1$s', t);
    execute format(
      'create trigger touch_%1$s before update on public.%1$s
         for each row execute function public.touch_updated_at()', t);
  end loop;
end $$;

-- ───────── 접근 규칙 (RLS): 로그인한 직원만 ─────────
do $$
declare t text;
begin
  foreach t in array array['customers', 'appointments', 'contact_logs', 'herb_alerts'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "staff only" on public.%I', t);
    execute format(
      'create policy "staff only" on public.%I
         for all to authenticated using (true) with check (true)', t);
  end loop;
end $$;

-- 로그인 안 한 사용자(anon)는 어떤 표에도 접근하지 못하게 확실히 막습니다.
revoke all on public.customers, public.appointments, public.contact_logs, public.herb_alerts from anon;

-- ───────── 실시간 반영: 한 기기에서 고치면 다른 기기에 바로 ─────────
do $$
declare t text;
begin
  foreach t in array array['customers', 'appointments', 'contact_logs', 'herb_alerts'] loop
    begin
      execute format('alter publication supabase_realtime add table public.%I', t);
    exception when duplicate_object then null;
    end;
  end loop;
end $$;
